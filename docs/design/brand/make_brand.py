"""Makes Kerf's brand files from the font and the drawings chosen in #166 (docs/design/brand.md).

Run from the repository root, in a Python virtual environment outside the repository (nothing is
added to the project, as with the fonts):

    python -m venv /tmp/kerf-brand && /tmp/kerf-brand/bin/pip install fonttools==4.68.0 brotli pillow uharfbuzz
    /tmp/kerf-brand/bin/python docs/design/brand/make_brand.py

It writes:
    apps/web/src/ui/wordmark-outline.ts   the wordmark's outline, for the Wordmark component
    apps/web/public/favicon.svg           the k fitted to a 16-unit grid; light or dark with the system
    apps/web/public/favicon.ico           the same k on a paper tile, 32 and 16 px
    apps/web/public/apple-touch-icon.png  180 px, for a phone's home screen
    apps/web/public/og.png                1200 by 630, the preview shown when a link is shared
"""

import io
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.basePen import BasePen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from PIL import Image, ImageChops, ImageDraw

ROOT = Path(__file__).resolve().parents[3]
FONT = ROOT / "apps/web/src/ui/fonts/AtkinsonHyperlegibleNext-Latin.woff2"
PUBLIC = ROOT / "apps/web/public"

# Colors from apps/web/src/ui/styles/tokens.css (C1, #43).
TEXT_LIGHT, TEXT_DARK = "#1a1d23", "#edebe7"
MUTED_LIGHT = "#545860"
PAPER = "#fbf9f5"

# The k at weight 700 with its ascender cut at 45 degrees, high on the right (round 3). The k is
# all straight lines, so it is kept as points, in font units with the baseline at 0.
SL, SR = 56.5625, 195.8123  # the stem's left and right edges
K_END = [(SL, 0), (SL, 708 - (SR - SL)), (SR, 708), (SR, 301.4373), (368.1874, 496), (533.3746, 496),
         (341.4996, 289.375), (550.2496, 0), (384.6875, 0), (248.9373, 190.0002), (SR, 132.6877), (SR, 0)]
K_WIDTH = 550.2496 - SL

# Pair spacing in font units. The font's own kerning at weight 700 is k-e -32, e-r 0, r-f +30
# (read with HarfBuzz); these even the gaps at display size (brand.html, round 3).
WORD = "kerf"
SPACING = {"ke": -30, "er": -14, "rf": 22}
TOP, OVERSHOOT = 720, 12  # the wordmark's box above and below the baseline


def instance(weight):
    font = TTFont(FONT)
    return instantiateVariableFont(font, {"wght": weight})


def num(n):
    return f"{n:.1f}".rstrip("0").rstrip(".")


def polygon_d(points):
    return "M" + "L".join(f"{num(x)} {num(y)}" for x, y in points) + "Z"


# ---- Wordmark outline ----

def wordmark_glyphs(font):
    """Each letter's x offset and glyph name, and the width of the ink. The box is cropped to the
    letters: x 0 is the k's stem and the width ends at the f's right edge, so the wordmark lines
    up with whatever it sits beside."""
    cmap, hmtx, glyphs = font.getBestCmap(), font["hmtx"], font.getGlyphSet()
    x, out = -SL, []
    for i, ch in enumerate(WORD):
        name = cmap[ord(ch)]
        out.append((x, name))
        if i == len(WORD) - 1:
            bounds = BoundsPen(glyphs)
            glyphs[name].draw(bounds)
            return out, x + bounds.bounds[2]
        x += hmtx[name][0] + SPACING[WORD[i:i + 2]]


def wordmark_d(font):
    """One SVG path with the baseline at y 0 and y increasing downward."""
    glyphs = font.getGlyphSet()
    letters, width = wordmark_glyphs(font)
    parts = []
    for x, name in letters:
        if name == font.getBestCmap()[ord("k")]:
            parts.append(polygon_d([(x + px, -py) for px, py in K_END]))
            continue
        pen = SVGPathPen(glyphs, ntos=num)
        glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, x, 0)))
        parts.append(pen.getCommands())
    return "".join(parts), width


def write_outline(font):
    d, width = wordmark_d(font)
    (ROOT / "apps/web/src/ui/wordmark-outline.ts").write_text(
        "// Generated by docs/design/brand/make_brand.py; do not edit. Atkinson Hyperlegible Next at\n"
        "// weight 700 with the end-cut k (#166), in font units: baseline at 0, the k's top at -708, cropped\n"
        "// to the letters' left and right edges.\n"
        f"export const WORDMARK = {{\n  width: {num(width)},\n  top: {TOP},\n  overshoot: {OVERSHOOT},\n"
        f"  d: '{d}',\n}} as const;\n"
    )


# ---- The k fitted to a 16-unit grid ----

def k_fitted():
    """The k 14 units tall on a 16-unit square, baseline at 15. Vertical and horizontal edges snap
    to whole units (stem 3 to 6, x-height at 5, top at 1) so they land on whole pixels at 16 and
    32 px; the 45 degree cut drops exactly the stem's 3 units; diagonal ends keep their positions."""
    s = 14 / 708
    out = []
    for x, y in K_END:
        fx, fy = 3 + (x - SL) * s, 15 - y * s
        if x in (SL, SR):
            fx = 3 if x == SL else 6
        if y in (0, 496, 708):
            fy = {0: 15, 496: 5, 708: 1}[y]
        if (x, y) == (SL, 708 - (SR - SL)):
            fy = 4
        out.append((fx, fy))
    return out


def write_favicon_svg():
    (PUBLIC / "favicon.svg").write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16"><title>Kerf</title>'
        f"<style>path{{fill:{TEXT_LIGHT}}}@media (prefers-color-scheme:dark){{path{{fill:{TEXT_DARK}}}}}</style>"
        f'<path d="{polygon_d(k_fitted())}"/></svg>\n'
    )


# ---- Rasterizing: contours drawn even-odd at 8 times the size, then averaged down ----

SUPER = 8


class Flatten(BasePen):
    """Collects contours as point lists, with curves cut into short straight pieces."""

    def __init__(self, glyphs=None):
        super().__init__(glyphs)
        self.contours, self.current = [], []

    def _moveTo(self, p):
        self.current = [p]

    def _lineTo(self, p):
        self.current.append(p)

    def _qCurveToOne(self, p1, p2):
        p0 = self.current[-1]
        for i in range(1, 13):
            t = i / 12
            self.current.append(((1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * p1[0] + t * t * p2[0],
                                 (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * p1[1] + t * t * p2[1]))

    def _curveToOne(self, p1, p2, p3):
        p0 = self.current[-1]
        for i in range(1, 17):
            t = i / 16
            a, b, c, d = (1 - t) ** 3, 3 * (1 - t) ** 2 * t, 3 * (1 - t) * t * t, t ** 3
            self.current.append((a * p0[0] + b * p1[0] + c * p2[0] + d * p3[0],
                                 a * p0[1] + b * p1[1] + c * p2[1] + d * p3[1]))

    def _closePath(self):
        self.contours.append(self.current)
        self.current = []

    _endPath = _closePath


def coverage(size, contours):
    """A grayscale mask of the contours (in pixels of the final size), filled even-odd."""
    w, h = size
    acc = Image.new("1", (w * SUPER, h * SUPER), 0)
    for contour in contours:
        layer = Image.new("1", acc.size, 0)
        ImageDraw.Draw(layer).polygon([(x * SUPER, y * SUPER) for x, y in contour], fill=1)
        acc = ImageChops.logical_xor(acc, layer)
    return acc.convert("L").resize(size, Image.BOX)


def paint(base, mask, color):
    base.paste(Image.new("RGBA", base.size, color), (0, 0), mask)
    return base


def tile(size, radius):
    w, h = size
    mask = Image.new("L", (w * SUPER, h * SUPER), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, w * SUPER - 1, h * SUPER - 1), radius * SUPER, fill=255)
    return paint(Image.new("RGBA", size, (0, 0, 0, 0)), mask.resize(size, Image.BOX), PAPER)


def k_contours(height, cx, baseline):
    s = height / 708
    left = cx - K_WIDTH * s / 2
    return [[(left + (x - SL) * s, baseline - y * s) for x, y in K_END]]


def write_ico():
    images = []
    for n in (32, 16):
        scale = n / 16
        img = tile((n, n), radius=scale)
        k = [[(x * scale, y * scale) for x, y in k_fitted()]]
        images.append(paint(img, coverage((n, n), k), TEXT_LIGHT))
    images[0].save(PUBLIC / "favicon.ico", sizes=[(32, 32), (16, 16)], append_images=images[1:])


def write_touch_icon():
    # Opaque, since iOS fills transparency with black; iOS rounds the corners itself. The k is
    # 60% of the height, inside Apple's safe area.
    size = (180, 180)
    img = Image.new("RGBA", size, PAPER)
    paint(img, coverage(size, k_contours(108, 90, 90 + 54)), TEXT_LIGHT)
    img.convert("RGB").save(PUBLIC / "apple-touch-icon.png", optimize=True)


def text_contours(font, text, px, x0, baseline, features=None):
    """A line of text shaped with HarfBuzz (so the font's kerning applies) as flattened contours."""
    buf = io.BytesIO()
    font.flavor = None
    font.save(buf)
    hb_font = hb.Font(hb.Face(buf.getvalue()))
    hb_buf = hb.Buffer()
    hb_buf.add_str(text)
    hb_buf.guess_segment_properties()
    hb.shape(hb_font, hb_buf, features or {})
    glyphs, order = font.getGlyphSet(), font.getGlyphOrder()
    s = px / font["head"].unitsPerEm
    pen, x = Flatten(glyphs), 0
    for info, pos in zip(hb_buf.glyph_infos, hb_buf.glyph_positions):
        glyphs[order[info.codepoint]].draw(TransformPen(pen, (s, 0, 0, -s, x0 + (x + pos.x_offset) * s, baseline)))
        x += pos.x_advance
    return pen.contours, x * s


def write_og(bold, regular):
    size = (1200, 630)
    img = Image.new("RGBA", size, PAPER)
    k_px = 200
    s = k_px / 708
    letters, width = wordmark_glyphs(bold)
    x0 = (size[0] - width * s) / 2
    baseline = 358  # centers the wordmark and tagline together
    glyphs = bold.getGlyphSet()
    pen = Flatten(glyphs)
    for x, name in letters:
        if name == bold.getBestCmap()[ord("k")]:
            pen.contours.append([(x0 + (x + px) * s, baseline - py * s) for px, py in K_END])
        else:
            glyphs[name].draw(TransformPen(pen, (s, 0, 0, -s, x0 + x * s, baseline)))
    paint(img, coverage(size, pen.contours), TEXT_LIGHT)
    tagline = "Plans for woodworking projects"
    _, w = text_contours(regular, tagline, 44, 0, 0)
    contours, _ = text_contours(regular, tagline, 44, (size[0] - w) / 2, baseline + 110)
    paint(img, coverage(size, contours), MUTED_LIGHT)
    img.convert("RGB").save(PUBLIC / "og.png", optimize=True)


def main():
    PUBLIC.mkdir(parents=True, exist_ok=True)
    bold, regular = instance(700), instance(400)
    write_outline(bold)
    write_favicon_svg()
    write_ico()
    write_touch_icon()
    write_og(bold, regular)


if __name__ == "__main__":
    main()
