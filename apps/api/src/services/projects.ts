// Projects and their stored snapshots (ARCHITECTURE.md, apps/api). Snapshots are generated by
// core and stored; reads parse them back and compare them with the template's current version.
// Regenerating is always explicit: a new snapshot is made only on create, when the parameters or
// structural inputs change, or on request.

export interface ProjectSummary {
  id: string;
  name: string;
  status: z.infer<typeof ProjectStatus>;
  templateId: string;
  templateVersion: number;
  /** Counts saves that changed the plan; a save or tick names the one it was made against. */
  revision: number;
  /** True when the template has a newer version than the one the snapshot was made with. */
  templateBehind: boolean;
  /**
   * Shopping lines bought, steps done, and the next step (#61), for the mode cards and the Resume
   * card. Null when the stored snapshot cannot be read.
   */
  progress: ProgressSummary | null;
  createdAt: string;
  updatedAt: string;
}

/** How long a deleted project waits in the trash before it is purged (owner, #21). */
const TRASH_DAYS = 30;
const DAY = 24 * 60 * 60 * 1000;

export interface TrashedProject extends ProjectSummary {
  deletedAt: string;
  purgeAt: string;
}

/** Raised when the backup file's shape changes, so a reader can tell which shape it holds. */
export const EXPORT_FORMAT_VERSION = 3;

export interface ProjectsExport {
  kind: 'kerf-export';
  formatVersion: typeof EXPORT_FORMAT_VERSION;
  exportedAt: string;
  projects: ExportedProject[];
  /** Projects in the trash, which can still be restored. Purged ones are gone. */
  deletedProjects: (ExportedProject & { deletedAt: string })[];
  /** Tool rows as stored, including types the library no longer has. */
  tools: Awaited<ReturnType<typeof exportTools>>;
}

export type ExportedProject = Omit<ProjectSummary, 'templateBehind' | 'progress'> & {
  snapshot: unknown;
  ticks: ProgressEntry[];
  /** Ticks cleared by a change and not yet dismissed, as stored (#444). */
  resets: { record: unknown; resetAt: string }[];
};

export interface Project extends ProjectSummary {
  /**
   * Null only when the stored snapshot cannot be read even after upgrading, which tests guard
   * against (decision 0014), or this code no longer has its template; `unreadable` says why.
   */
  snapshot: ProjectSnapshot | null;
  unreadable?: { reason: string; message: string };
  /** Null when the snapshot cannot be read, or comparing it with the template fails. */
  version: VersionReport | null;
  /**
   * The build steps (#105, #52), with methods chosen from the current tool inventory on each read,
   * and the key of that inventory so a client can tell when they are stale. In the project
   * response so the shop view needs no other request. Null when the snapshot cannot be read or
   * choosing them fails.
   */
  steps: BuildSteps | null;
  /** What has been ticked off (#57), so the plan and its modes need no other request. */
  ticks: ProgressEntry[];
  /**
   * Ticks cleared by earlier saves and not yet dismissed (#444), each read against the current
   * plan, with when it was cleared. Empty when the snapshot cannot be read.
   */
  resets: ProjectReset[];
  /**
   * After a save that regenerated the snapshot: the ticks it cleared because their item is gone
   * or has other numbers (#57). Absent when nothing was regenerated.
   */
  progressReset?: ProgressReset[];
}

/** A reset as the owner reads it, and when it was made, which dismissing it names. */
export type ProjectReset = ResetNote & { resetAt: string };

/** A snapshot generated from proposed changes and not saved, with what it changes. */
export interface Preview {
  snapshot: ProjectSnapshot;
  /** Paths in the template's plan whose values differ from the stored snapshot's. */
  changes: Change[];
  truncated: boolean;
  /** The ticks saving would clear, each against the previewed plan (#444). */
  progressReset: ResetNote[];
}

/**
 * The plan's drawings (#90, #91), drawn by core from the stored snapshot on each read, in a
 * request of their own: a large plan's are megabytes. Not stored: a view of the numbers the snapshot
 * holds. Null when the snapshot cannot be read or drawing it fails.
 */
export interface ProjectDrawings {
  drawings: geometry.Drawings | null;
  /** The plan's sub-assemblies (#647), listed only: each one's drawings come on their own. */
  subAssemblies: geometry.SubAssemblySummary[];
}

/**
 * One build step's action drawing (#118), drawn on read like the rest, in a request of its own
 * (#635): together they are most of a large plan's drawings. Null for a step with none, or when
 * the snapshot cannot be read or drawing it fails.
 */
export interface ProjectStepDrawing {
  drawing: geometry.Drawing | null;
}

/**
 * One sub-assembly's assembled and exploded views, drawn on read, in a request of its own like a
 * step's. Null when the snapshot cannot be read or drawing it fails.
 */
export interface ProjectSubAssemblyDrawings {
  drawings: geometry.SubAssemblyDrawings | null;
}

/** A plan's assembled and exploded views from one corner. */
type CornerViews = Pick<geometry.Drawings, 'isometric' | 'exploded'>;

export type Result<T> =
  | { ok: true; value: T }
  | {
      ok: false;
      /** `missing-template`: a stored project names a template this code no longer has. */
      error:
        | 'not-found'
        | 'unknown-template'
        | 'missing-template'
        | 'unreadable-snapshot'
        /** A sub-assembly the plan does not have. */
        | 'unknown-sub-assembly';
    }
  | { ok: false; error: 'invalid-project'; issues: Issue[] }
  | { ok: false; error: 'unknown-progress'; items: { kind: string; key: string }[] }
  /** A confirmation for a value the stored plan does not hold as a suggestion. */
  | { ok: false; error: 'unknown-suggestion'; fields: { from: string; path: string }[] }
  /** Another save changed the plan since this one's revision; `revision` is the current one. */
  | { ok: false; error: 'stale-project'; revision: number };

type Row = typeof projects.$inferSelect;

/** What the projects list and the trash read: no snapshot (#636). */
const summaryColumns = {
  id: projects.id,
  name: projects.name,
  status: projects.status,
  templateId: projects.templateId,
  templateVersion: projects.templateVersion,
  revision: projects.revision,
  progressOutline: projects.progressOutline,
  progressOutlineRevision: projects.progressOutlineRevision,
  deletedAt: projects.deletedAt,
  createdAt: projects.createdAt,
  updatedAt: projects.updatedAt,
};
type SummaryRow = { [K in keyof typeof summaryColumns]: Row[K] };

type Stored =
  | {
      ok: true;
      template: TemplateDefinition;
      snapshot: ProjectSnapshot;
      outputs: ReturnType<TemplateDefinition['storedOutputs']['parse']>;
    }
  | { ok: false; reason: string; message: string };

/** A project read after a regenerating save, with the ticks the save cleared. */
function withReset(
  result: Result<Project>,
  progressReset: ProgressReset[] | undefined,
): Result<Project> {
  if (!result.ok || progressReset === undefined) return result;
  return { ok: true, value: { ...result.value, progressReset } };
}

export function createProjectService(deps: {
  db: Database;
  templates: readonly TemplateDefinition[];
  now: () => Date;
}) {
  const { db, templates, now } = deps;
  const findTemplate = (id: string) => templates.find((t) => t.id === id);

  /** The stored snapshot, upgraded to the current shape if it was stored in an older one. */
  const read = (row: Row) => readSnapshot(templates, row.snapshot);

  /**
   * The row's snapshot read once, with its template and its outputs parsed by the template's
   * schema, for everything a read draws or counts from it; or why it cannot be read.
   */
  function readStored(row: Row): Stored {
    const template = findTemplate(row.templateId);
    if (!template) {
      return {
        ok: false,
        reason: 'unknown-template',
        message: `No template has the ID "${row.templateId}".`,
      };
    }
    const result = read(row);
    if (!result.ok) return result;
    const { snapshot } = result;
    return {
      ok: true,
      template,
      snapshot,
      outputs: template.storedOutputs.parse(snapshot.outputs),
    };
  }

  /** Progress counted from the ticks, or null when the stored plan cannot be counted. */
  function progressOf(row: Row, stored: Stored, ticks: readonly ProgressEntry[]) {
    if (!stored.ok) return null;
    try {
      return progressSummary(stored.template, stored.outputs, ticks);
    } catch (error) {
      console.error(`project ${row.id}: progress could not be counted`, error);
      return null;
    }
  }

  /** The row's summary, with its progress as counted from its ticks. */
  function summary(row: SummaryRow, progress: ProgressSummary | null): ProjectSummary {
    const template = findTemplate(row.templateId);
    return {
      id: row.id,
      name: row.name,
      status: ProjectStatus.parse(row.status),
      templateId: row.templateId,
      templateVersion: row.templateVersion,
      revision: row.revision,
      templateBehind: template !== undefined && row.templateVersion < template.version,
      progress,
      createdAt: row.createdAt.toISOString(),
      updatedAt: row.updatedAt.toISOString(),
    };
  }

  /** What `draw` returns, or null if it throws, so one broken view does not stop the project opening. */
  function drawn<T>(row: Row, what: string, draw: () => T): T | null {
    try {
      return draw();
    } catch (error) {
      console.error(`project ${row.id}: ${what} could not be drawn`, error);
      return null;
    }
  }

  /** The recorded resets as notes against the stored plan, or none if they cannot be read. */
  function notesOf(row: Row, stored: Stored, resets: readonly StoredReset[]): ProjectReset[] {
    if (!stored.ok || resets.length === 0) return [];
    const notes = drawn(row, 'the reset notes', () =>
      resetNotes(
        stored.template,
        stored.outputs,
        resets.map((r) => r.record),
      ),
    );
    return (notes ?? []).map((note, i) => ({ ...note, resetAt: resets[i]?.resetAt ?? '' }));
  }

  async function view(row: Row): Promise<Result<Project>> {
    const stored = readStored(row);
    const ticks = await readProgress(db, row.id);
    const resets = notesOf(row, stored, await readResets(db, row.id));
    if (!stored.ok) {
      return {
        ok: true,
        value: {
          ...summary(row, null),
          snapshot: null,
          unreadable: { reason: stored.reason, message: stored.message },
          version: null,
          steps: null,
          ticks,
          resets,
        },
      };
    }
    const { snapshot, template, outputs } = stored;
    const inventory = await getInventory(db);
    return {
      ok: true,
      value: {
        ...summary(row, progressOf(row, stored, ticks)),
        ticks,
        resets,
        snapshot,
        version: drawn(row, 'the version report', () => compareWithCurrent(template, snapshot)),
        steps: drawn(row, 'the build steps', () => planSteps(template, outputs, inventory)),
      },
    };
  }

  function generate(
    templateId: string,
    params: unknown,
    structuralInputs: unknown,
    suggested: readonly SuggestedValue[] = [],
  ) {
    const template = findTemplate(templateId);
    if (!template) return { ok: false, error: 'unknown-template' } as const;
    const result = createSnapshot(template, params, structuralInputs, suggested);
    if (!result.ok) return { ok: false, error: 'invalid-project', issues: result.issues } as const;
    return { ok: true, snapshot: result.output, template } as const;
  }

  /**
   * A new project's snapshot. Started from the template's questions, it records which values are
   * still Kerf's suggestions, worked out here from the answers (#417), so no client can store a
   * suggestion as entered.
   */
  function generateNew(input: NewProjectPreview) {
    const template = findTemplate(input.templateId);
    if (!template) return { ok: false, error: 'unknown-template' } as const;
    const inputs = input.structuralInputs ?? {};
    if (input.answers === undefined) return generate(input.templateId, input.params, inputs);
    const found = suggestedFor(template, input.answers, input.params, inputs);
    if (!found.ok) return { ok: false, error: 'invalid-project', issues: found.issues } as const;
    return generate(input.templateId, input.params, inputs, found.suggested);
  }

  /**
   * The suggestions a regenerated snapshot keeps from the stored one: those whose values it left as
   * they were, and those filled for what the stored one lacked. Read from the row as locked, so a
   * confirmation made since this save's revision stands.
   */
  function carried(
    template: TemplateDefinition,
    stored: ProjectSnapshot,
    next: ProjectSnapshot,
  ): ProjectSnapshot {
    return { ...next, suggested: suggestedAfter(template, stored, next) };
  }

  /** The values changed, and the stored ones for the rest, with what an older plan lacks filled. */
  function valuesFor(
    templateId: string,
    stored: ProjectSnapshot,
    changes: Pick<ProjectChanges, 'params' | 'structuralInputs'> = {},
  ) {
    const template = findTemplate(templateId);
    const filled = template ? fillMissing(template, stored) : stored;
    return {
      params: changes.params ?? filled.params,
      structuralInputs: changes.structuralInputs ?? filled.structuralInputs,
    };
  }

  /** A snapshot's columns, with its progress outline made at the revision it is saved at. */
  function snapshotColumns(template: TemplateDefinition, s: ProjectSnapshot, revision: number) {
    let progressOutline: ProgressOutline | null = null;
    try {
      progressOutline = outlineOfSnapshot(template, s);
    } catch (error) {
      console.error("a saved plan's progress could not be counted", error);
    }
    return {
      templateVersion: s.templateVersion,
      snapshot: s,
      progressOutline,
      progressOutlineRevision: progressOutline ? revision : null,
    };
  }

  /**
   * Each row's progress outline: the stored one when it was made at the row's revision, otherwise
   * read from the snapshot once and stored for the next read. Null when the snapshot cannot be
   * read or counted.
   */
  async function outlines(
    rows: readonly SummaryRow[],
  ): Promise<Map<string, ProgressOutline | null>> {
    const found = new Map<string, ProgressOutline | null>();
    const stale: string[] = [];
    for (const row of rows) {
      const stored =
        row.progressOutlineRevision === row.revision
          ? ProgressOutline.safeParse(row.progressOutline)
          : undefined;
      if (stored?.success) found.set(row.id, stored.data);
      else stale.push(row.id);
    }
    if (stale.length === 0) return found;
    for (const row of await db.select().from(projects).where(inArray(projects.id, stale))) {
      const outline = outlineOf(templates, row);
      found.set(row.id, outline);
      if (!outline) continue;
      // Only at the revision read: a save since then raised it and wrote its own outline.
      await db
        .update(projects)
        .set({ progressOutline: outline, progressOutlineRevision: row.revision })
        .where(and(eq(projects.id, row.id), eq(projects.revision, row.revision)));
    }
    return found;
  }

  /** The rows' summaries, with progress counted from their outlines and ticks. */
  async function summaries(rows: readonly SummaryRow[]): Promise<ProjectSummary[]> {
    const outlined = await outlines(rows);
    const ticks = await readAllProgress(db);
    return rows.map((row) => {
      const outline = outlined.get(row.id) ?? null;
      return summary(row, outline ? countProgress(outline, ticks.get(row.id) ?? []) : null);
    });
  }

  /** A project that is not in the trash. Everything but the trash reads only these. */
  const live = (id: string) => and(eq(projects.id, id), isNull(projects.deletedAt));

  async function load(id: string): Promise<Row | undefined> {
    const [row] = await db.select().from(projects).where(live(id));
    return row;
  }

  /** The row, locked until the transaction ends, so a check against it holds for the write. */
  async function lock(tx: Database, id: string): Promise<Row | undefined> {
    const [row] = await tx.select().from(projects).where(live(id)).for('update');
    return row;
  }

  /** Projects in the trash longer than TRASH_DAYS are deleted for good, with their history. */
  async function purge(): Promise<void> {
    const before = new Date(now().getTime() - TRASH_DAYS * DAY);
    await db.delete(projects).where(lt(projects.deletedAt, before));
  }

  type Failure = Exclude<Result<never>, { ok: true }>;
  const stale = (row: Row): Failure => ({
    ok: false,
    error: 'stale-project',
    revision: row.revision,
  });

  return {
    async list(): Promise<ProjectSummary[]> {
      const rows = await db
        .select(summaryColumns)
        .from(projects)
        .where(isNull(projects.deletedAt))
        .orderBy(desc(projects.updatedAt));
      return summaries(rows);
    },

    async get(id: string): Promise<Result<Project>> {
      const row = await load(id);
      return row ? view(row) : { ok: false, error: 'not-found' };
    },

    /** The plan's assembled and exploded views seen from one corner (#364), drawn on read. */
    async views(id: string, corner: geometry.Corner): Promise<Result<CornerViews>> {
      const row = await load(id);
      if (!row) return { ok: false, error: 'not-found' };
      if (!findTemplate(row.templateId)) return { ok: false, error: 'missing-template' };
      const stored = readStored(row);
      if (!stored.ok) return { ok: false, error: 'unreadable-snapshot' };
      return { ok: true, value: cornerViews(stored.template, stored.outputs, corner) };
    },

    /**
     * The plan's drawings, drawn on read. A plan that cannot be read or drawn has none, as it
     * opens without them; drawing errors are logged.
     */
    async drawings(id: string): Promise<Result<ProjectDrawings>> {
      const row = await load(id);
      if (!row) return { ok: false, error: 'not-found' };
      const stored = readStored(row);
      if (!stored.ok) return { ok: true, value: { drawings: null, subAssemblies: [] } };
      const { template, outputs } = stored;
      return {
        ok: true,
        value: {
          drawings: drawn(row, 'the drawings', () => projectDrawings(template, outputs)),
          subAssemblies:
            drawn(row, 'the sub-assemblies', () => subAssemblies(template, outputs)) ?? [],
        },
      };
    },

    /** One step's action drawing, drawn on read; none for a step that has none. */
    async stepDrawing(id: string, stepId: string): Promise<Result<ProjectStepDrawing>> {
      const row = await load(id);
      if (!row) return { ok: false, error: 'not-found' };
      const stored = readStored(row);
      if (!stored.ok) return { ok: true, value: { drawing: null } };
      const { template, outputs } = stored;
      const drawing = drawn(row, `the drawing for step ${stepId}`, () =>
        stepDrawing(template, outputs, stepId),
      );
      return { ok: true, value: { drawing } };
    },

    /**
     * One sub-assembly's views, drawn on read. A group the plan does not list is not found; a plan
     * that cannot be read lists none, so it answers the same.
     */
    async subAssemblyDrawings(
      id: string,
      groupId: string,
    ): Promise<Result<ProjectSubAssemblyDrawings>> {
      const row = await load(id);
      if (!row) return { ok: false, error: 'not-found' };
      const stored = readStored(row);
      if (!stored.ok) return { ok: false, error: 'unknown-sub-assembly' };
      const { template, outputs } = stored;
      const listed = drawn(row, 'the sub-assemblies', () => subAssemblies(template, outputs));
      if (listed && !listed.some((g) => g.id === groupId)) {
        return { ok: false, error: 'unknown-sub-assembly' };
      }
      const drawings = drawn(row, `the drawings for sub-assembly ${groupId}`, () =>
        subAssemblyDrawings(template, outputs, groupId),
      );
      return { ok: true, value: { drawings } };
    },

    async create(input: NewProject): Promise<Result<Project>> {
      const generated = generateNew(input);
      if (!generated.ok) return generated;
      const at = now();
      const row = await db.transaction(async (tx) => {
        const [inserted] = await tx
          .insert(projects)
          .values({
            name: input.name,
            status: input.status,
            templateId: input.templateId,
            ...snapshotColumns(generated.template, generated.snapshot, 1),
            revision: 1,
            createdAt: at,
            updatedAt: at,
          })
          .returning();
        if (!inserted) throw new Error('Insert returned no row');
        await writeHistory(tx, generated.template, inserted.id, generated.snapshot, at);
        return inserted;
      });
      return view(row);
    },

    /**
     * Changing parameters or inputs regenerates with the template's current version. A change to
     * the plan made against an older revision is refused (#207); a status change alone is not.
     */
    async update(id: string, changes: ProjectChanges): Promise<Result<Project>> {
      const plan = changesPlan(changes);
      const at = now();
      let progressReset: ProgressReset[] | undefined;
      // Generating can take a while, so it runs before the row is locked, from the row as this
      // save's revision left it. The revision is checked again under the lock: if it moved, the
      // values generated from are no longer the stored ones.
      let saved: { snapshot: ProjectSnapshot; template: TemplateDefinition } | undefined;
      let before: { snapshot: ProjectSnapshot; template: TemplateDefinition } | undefined;
      if (changes.params !== undefined || changes.structuralInputs !== undefined) {
        const row = await load(id);
        if (!row) return { ok: false, error: 'not-found' };
        if (changes.revision !== row.revision) return stale(row);
        const stored = read(row);
        if (!stored.ok) return { ok: false, error: 'unreadable-snapshot' };
        const values = valuesFor(row.templateId, stored.snapshot, changes);
        const generated = generate(row.templateId, values.params, values.structuralInputs);
        if (!generated.ok) return generated;
        saved = generated;
        before = { snapshot: stored.snapshot, template: generated.template };
      }
      const outcome = await db.transaction(async (tx): Promise<Row | Failure> => {
        const row = await lock(tx, id);
        if (!row) return { ok: false, error: 'not-found' };
        if (plan && changes.revision !== row.revision) return stale(row);
        if (saved) {
          const locked = read(row);
          if (!locked.ok) return { ok: false, error: 'unreadable-snapshot' };
          saved = { ...saved, snapshot: carried(saved.template, locked.snapshot, saved.snapshot) };
        }
        const [updated] = await tx
          .update(projects)
          .set({
            ...(changes.name !== undefined ? { name: changes.name } : {}),
            ...(changes.status !== undefined ? { status: changes.status } : {}),
            ...(saved ? snapshotColumns(saved.template, saved.snapshot, row.revision + 1) : {}),
            ...(plan ? { revision: row.revision + 1 } : {}),
            updatedAt: at,
          })
          .where(eq(projects.id, id))
          .returning();
        if (!updated) return { ok: false, error: 'not-found' };
        // A name or status change keeps the snapshot, so its history and progress stand.
        if (saved && before) {
          await writeHistory(tx, saved.template, id, saved.snapshot, at);
          progressReset = await resetProgress(tx, id, before, saved, at);
        }
        return updated;
      });
      if ('ok' in outcome) return outcome;
      return withReset(await view(outcome), progressReset);
    },

    /**
     * What saving these changes would produce, compared with the stored snapshot, without saving
     * anything (#56). Takes the same changes as `update`; a name or status change alone previews
     * the stored parameters and inputs with the current template version.
     */
    async preview(id: string, changes: ProjectChanges): Promise<Result<Preview>> {
      const row = await load(id);
      if (!row) return { ok: false, error: 'not-found' };
      const template = findTemplate(row.templateId);
      if (!template) return { ok: false, error: 'missing-template' };
      const stored = read(row);
      if (!stored.ok) return { ok: false, error: 'unreadable-snapshot' };
      const values = valuesFor(row.templateId, stored.snapshot, changes);
      const generated = generate(row.templateId, values.params, values.structuralInputs);
      if (!generated.ok) return generated;
      const snapshot = carried(template, stored.snapshot, generated.snapshot);
      const { records } = await resetsFor(
        db,
        id,
        { template, snapshot: stored.snapshot },
        { template, snapshot },
      );
      const outputs = template.storedOutputs.parse(snapshot.outputs);
      return {
        ok: true,
        value: {
          snapshot,
          ...compareSnapshots(template, stored.snapshot, snapshot),
          progressReset: resetNotes(template, outputs, records),
        },
      };
    },

    /**
     * What creating a project from these values would produce, without saving anything (#98).
     * There is no saved plan to compare with, so nothing is marked as changed.
     */
    previewNew(input: NewProjectPreview): Result<Preview> {
      const generated = generateNew(input);
      if (!generated.ok) return generated;
      return {
        ok: true,
        value: { snapshot: generated.snapshot, changes: [], truncated: false, progressReset: [] },
      };
    },

    /**
     * Regenerates from the stored parameters and inputs with the current template version. The
     * plan changes, so its revision does too. A regeneration asked for on an older revision is
     * refused: the owner approved the changes computed from that revision's values.
     */
    async regenerate(id: string, request: ProjectRegenerate): Promise<Result<Project>> {
      const at = now();
      let progressReset: ProgressReset[] | undefined;
      // Generated before the lock and checked again under it, as a save is.
      const row = await load(id);
      if (!row) return { ok: false, error: 'not-found' };
      if (request.revision !== row.revision) return stale(row);
      const stored = read(row);
      if (!stored.ok) return { ok: false, error: 'unreadable-snapshot' };
      const values = valuesFor(row.templateId, stored.snapshot);
      const generated = generate(row.templateId, values.params, values.structuralInputs);
      if (!generated.ok) return generated;
      const outcome = await db.transaction(async (tx): Promise<Row | Failure> => {
        const locked = await lock(tx, id);
        if (!locked) return { ok: false, error: 'not-found' };
        if (request.revision !== locked.revision) return stale(locked);
        const current = read(locked);
        if (!current.ok) return { ok: false, error: 'unreadable-snapshot' };
        const snapshot = carried(generated.template, current.snapshot, generated.snapshot);
        const [updated] = await tx
          .update(projects)
          .set({
            ...snapshotColumns(generated.template, snapshot, locked.revision + 1),
            revision: locked.revision + 1,
            updatedAt: at,
          })
          .where(eq(projects.id, id))
          .returning();
        if (!updated) return { ok: false, error: 'not-found' };
        await writeHistory(tx, generated.template, id, snapshot, at);
        progressReset = await resetProgress(
          tx,
          id,
          { snapshot: stored.snapshot, template: generated.template },
          { snapshot, template: generated.template },
          at,
        );
        return updated;
      });
      if ('ok' in outcome) return outcome;
      return withReset(await view(outcome), progressReset);
    },

    /** What has been ticked off in a project (#57). */
    async progress(id: string): Promise<Result<ProgressEntry[]>> {
      if (!(await load(id))) return { ok: false, error: 'not-found' };
      return { ok: true, value: await readProgress(db, id) };
    },

    /**
     * Sets and clears ticks, and returns every tick. Ticks made against an older revision of the
     * plan are refused (#207): an item's key can outlive a change to its numbers. A tick on an
     * item the stored plan does not have is refused too, with nothing saved, so a client learns
     * which queued ticks went stale. Clearing one is allowed: it leaves no tick either way. Status
     * follows (`statusAfterTicks`), and the response carries it. The check, the write, and the
     * status move together.
     */
    async setProgress(
      id: string,
      changes: ProgressChanges,
    ): Promise<Result<{ ticks: ProgressEntry[]; status: ProjectSummary['status'] }>> {
      return db.transaction(async (tx) => {
        const row = await lock(tx, id);
        if (!row) return { ok: false, error: 'not-found' };
        if (changes.revision !== row.revision) return stale(row);
        const template = findTemplate(row.templateId);
        if (!template) return { ok: false, error: 'missing-template' };
        const stored = read(row);
        if (!stored.ok) return { ok: false, error: 'unreadable-snapshot' };
        const known = new Set(itemsOf(template, stored.snapshot).map(progressId));
        const unknown = changes.changes.filter((c) => c.done && !known.has(progressId(c)));
        if (unknown.length > 0) {
          return {
            ok: false,
            error: 'unknown-progress',
            items: unknown.map(({ kind, key }) => ({ kind, key })),
          };
        }
        const outputs = template.storedOutputs.parse(stored.snapshot.outputs);
        const before = progressSummary(template, outputs, await readProgress(tx, id));
        const at = now();
        await writeProgress(tx, id, changes.changes, at);
        const ticks = await readProgress(tx, id);
        const current = ProjectStatus.parse(row.status);
        const status = statusAfterTicks(
          current,
          changes.changes,
          before,
          progressSummary(template, outputs, ticks),
        );
        if (status !== current) {
          await tx.update(projects).set({ status, updatedAt: at }).where(eq(projects.id, id));
        }
        return { ok: true, value: { ticks, status } };
      });
    },

    /**
     * Dismisses recorded resets (#444). Changes no number, so it takes no revision: each names
     * the time it was made, so a dismissal sent from an older view cannot clear a later reset.
     */
    async dismissResets(id: string, request: ResetDismissals): Promise<Result<ProjectReset[]>> {
      const row = await load(id);
      if (!row) return { ok: false, error: 'not-found' };
      await dismissResets(db, id, request.resets);
      return { ok: true, value: notesOf(row, readStored(row), await readResets(db, id)) };
    },

    /**
     * Confirms or unconfirms suggested values, ticked in the structural review (#417). Refused on
     * an older revision of the plan, as a tick is (0018). A confirmation changes no number, so it
     * leaves the revision and the status as they are, and a form open on another device can still
     * save: its save keeps the confirmation, read under the lock. The stored snapshot keeps its
     * shape; only its list of suggestions changes.
     */
    async confirmSuggested(
      id: string,
      request: SuggestedChanges,
    ): Promise<Result<{ suggested: SuggestedValue[] }>> {
      return db.transaction(async (tx) => {
        const row = await lock(tx, id);
        if (!row) return { ok: false, error: 'not-found' };
        if (request.revision !== row.revision) return stale(row);
        const stored = read(row);
        if (!stored.ok) return { ok: false, error: 'unreadable-snapshot' };
        const confirmed = confirmSuggested(stored.snapshot.suggested, request.changes);
        if (!confirmed.ok)
          return { ok: false, error: 'unknown-suggestion', fields: confirmed.unknown };
        await tx
          .update(projects)
          .set({
            snapshot: { ...(row.snapshot as object), suggested: confirmed.suggested },
            updatedAt: now(),
          })
          .where(eq(projects.id, id));
        return { ok: true, value: { suggested: confirmed.suggested } };
      });
    },

    /** Moves the project to the trash, where it can be restored for TRASH_DAYS. */
    async remove(id: string): Promise<Result<null>> {
      const moved = await db
        .update(projects)
        .set({ deletedAt: now() })
        .where(live(id))
        .returning({ id: projects.id });
      return moved.length > 0 ? { ok: true, value: null } : { ok: false, error: 'not-found' };
    },

    /** The projects in the trash, most recently deleted first, with when each is purged. */
    async trash(): Promise<TrashedProject[]> {
      await purge();
      const rows = await db
        .select(summaryColumns)
        .from(projects)
        .where(isNotNull(projects.deletedAt))
        .orderBy(desc(projects.deletedAt));
      const listed = await summaries(rows);
      return rows.map((row, i) => {
        const deletedAt = row.deletedAt as Date;
        return {
          ...(listed[i] as ProjectSummary),
          deletedAt: deletedAt.toISOString(),
          purgeAt: new Date(deletedAt.getTime() + TRASH_DAYS * DAY).toISOString(),
        };
      });
    },

    /** Takes a project out of the trash, as it was. */
    async restore(id: string): Promise<Result<null>> {
      const restored = await db
        .update(projects)
        .set({ deletedAt: null })
        .where(and(eq(projects.id, id), isNotNull(projects.deletedAt)))
        .returning({ id: projects.id });
      return restored.length > 0 ? { ok: true, value: null } : { ok: false, error: 'not-found' };
    },

    /** Permanent, from the trash only: its history and progress rows go with it (they cascade). */
    async purgeOne(id: string): Promise<Result<null>> {
      const deleted = await db
        .delete(projects)
        .where(and(eq(projects.id, id), isNotNull(projects.deletedAt)))
        .returning({ id: projects.id });
      return deleted.length > 0 ? { ok: true, value: null } : { ok: false, error: 'not-found' };
    },

    /**
     * Every project, trashed ones apart in `deletedProjects`, as stored, with its ticks and resets, and the
     * tool rows as stored: a copy the owner keeps, since the free database restores only the last
     * few hours (#21).
     */
    async exportAll(): Promise<ProjectsExport> {
      await purge();
      const rows = await db.select().from(projects).orderBy(desc(projects.updatedAt));
      const ticks = await readAllProgress(db);
      const resets = await readAllResets(db);
      const exported = (row: (typeof rows)[number]): ExportedProject => ({
        id: row.id,
        name: row.name,
        status: ProjectStatus.parse(row.status),
        templateId: row.templateId,
        templateVersion: row.templateVersion,
        revision: row.revision,
        createdAt: row.createdAt.toISOString(),
        updatedAt: row.updatedAt.toISOString(),
        snapshot: row.snapshot,
        ticks: ticks.get(row.id) ?? [],
        resets: resets.get(row.id) ?? [],
      });
      return {
        kind: 'kerf-export',
        formatVersion: EXPORT_FORMAT_VERSION,
        exportedAt: now().toISOString(),
        projects: rows.filter((row) => row.deletedAt === null).map(exported),
        deletedProjects: rows
          .filter((row) => row.deletedAt !== null)
          .map((row) => ({ ...exported(row), deletedAt: (row.deletedAt as Date).toISOString() })),
        tools: await exportTools(db),
      };
    },
  };
}

